#!/usr/bin/env node
/**
 * 构建期生成中文断点数据。
 *
 * 使用 Node 自带 ICU 的 Intl.Segmenter('zh', { granularity: 'word' })，
 * 为游戏里全部固定文案和模板变量展开值预计算词边界，写到
 * cocos/assets/scripts/ui/WordBreakData.ts。运行时有 Intl.Segmenter 时直接
 * 用运行时分词；没有时退回这份预计算数据 + 词表。
 *
 * 用法：node --import tsx scripts/gen-wordbreak.mjs
 */
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { allWordBreakTexts } from '../cocos/assets/scripts/ui/WordBreakCorpus.ts';
import { ATOMIC_NAMES, ATOMIC_PHRASES } from '../cocos/assets/scripts/ui/WordBreak.ts';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outFile = join(root, 'cocos', 'assets', 'scripts', 'ui', 'WordBreakData.ts');

if (typeof Intl === 'undefined' || typeof Intl.Segmenter !== 'function') {
  throw new Error('当前 Node 没有 Intl.Segmenter，无法生成断点数据');
}

const segmenter = new Intl.Segmenter('zh', { granularity: 'word' });
const texts = allWordBreakTexts();
const breaks = new Map();
const lexicon = new Set();

function boundaryOffsets(text) {
  const offsets = [];
  for (const part of segmenter.segment(text)) {
    if (part.index > 0) offsets.push(part.index);
    if (part.segment) lexicon.add(part.segment);
  }
  return offsets;
}

for (const text of texts) {
  const offsets = boundaryOffsets(text);
  if (offsets.length > 0) {
    breaks.set(text, offsets);
    // 同一文案的普通空格版也登记一份（运行时光标/旧语料可能仍是普通空格）。
    const spaced = text.replace(/\u00A0/g, ' ');
    if (spaced !== text) breaks.set(spaced, offsets);
  }
}

// 不可断品名/签头词也写进词表，保证没有 Intl.Segmenter 的微信真机同样覆盖。
for (const word of [...ATOMIC_NAMES, ...ATOMIC_PHRASES]) {
  if (word && word !== '\n' && !/^\s+$/.test(word)) lexicon.add(word);
}

// 词表用于没有 Intl.Segmenter 的运行时：按最长已知词切分未知动态文案。
const words = Array.from(lexicon)
  .filter((word) => word && word !== '\n' && !/^\s+$/.test(word))
  .sort((a, b) => b.length - a.length || a.localeCompare(b));

const lines = [];
lines.push('// Generated by scripts/gen-wordbreak.mjs — do not edit by hand.');
lines.push('// Node ICU Intl.Segmenter(\'zh\', { granularity: \'word\' }) precomputed boundaries.');
lines.push(`export const WORD_BREAK_DATA_VERSION = ${JSON.stringify(`icu-${process.versions.icu ?? 'unknown'}`)};`);
lines.push(`export const WORD_LEXICON: string[] = ${JSON.stringify(words)};`);
lines.push('export const WORD_BREAKS: Record<string, number[]> = {');
for (const [text, offsets] of breaks) {
  lines.push(`  ${JSON.stringify(text)}: [${offsets.join(', ')}],`);
}
lines.push('};');
lines.push('');
writeFileSync(outFile, lines.join('\n'), 'utf8');
console.log(`[gen-wordbreak] ${breaks.size} 条文案，${words.length} 个词，ICU ${process.versions.icu ?? 'unknown'} -> ${outFile}`);
