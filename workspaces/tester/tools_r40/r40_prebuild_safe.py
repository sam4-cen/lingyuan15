#!/usr/bin/env python3
import argparse
import hashlib
import json
import os
from datetime import datetime, timezone
from pathlib import Path

EXPECTED_COMMIT = "d3d65b662c29b5a9d2103a011a5c2bb87f3a2edb"
EXPECTED_SHORT = "d3d65b6"
EXPECTED_VERSION = "r40"
EXPECTED_TAG = "r40 d3d65b6"

SOURCE_SCRIPTS = {
    "assets/scripts/ui/MapLayout.ts": "b7db7976c14324a7eb57835ee4daba74a36ad267e2e8ce29492b7d7e567fd134",
    "assets/scripts/GameRoot.ts": "7fd8f57703f990b7e3327536dc084ff12daf20ec17eaac1030d7261a987b2ecf",
}
BUILD_FILES = [
    "game.js",
    "game.json",
    "project.config.json",
    "project.private.config.json",
]
ORIGINAL_PATHS = {
    Path("/Users/[REDACTED]/Documents/lingyuan15"),
    Path("/workspace/lingyuan15"),
}

def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        while True:
            chunk = f.read(1024 * 1024)
            if not chunk:
                break
            h.update(chunk)
    return h.hexdigest()

def require_new_copy(project_root):
    root = project_root.resolve()
    for original in ORIGINAL_PATHS:
        if root == original.resolve():
            raise SystemExit("REFUSE_ORIGINAL_PROJECT: " + str(root))
    if not (root / "assets" / "scripts").is_dir():
        raise SystemExit("NOT_COCOS_PROJECT_ROOT: " + str(root))
    return root

def verify_sources(root):
    for rel, expected in SOURCE_SCRIPTS.items():
        p = root / rel
        if not p.is_file():
            raise SystemExit("SOURCE_MISSING: " + str(p))
        actual = sha256(p)
        if actual != expected:
            raise SystemExit("SOURCE_HASH_MISMATCH: " + rel + " " + actual)

def version_text():
    return (
        "// Generated by r40_prebuild_safe.py - do not edit by hand.\n"
        'export const BUILD_VERSION = "r40";\n'
        'export const BUILD_HASH = "d3d65b6";\n'
        'export const BUILD_TAG = "r40 d3d65b6";\n'
        "export const IS_TEST_BUILD = true;\n"
    )

def write_version(root):
    verify_sources(root)
    target = root / "assets" / "scripts" / "Version.ts"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(version_text(), encoding="utf-8")
    print("VERSION_WRITTEN: " + str(target))

def measure_dir(root, skip_subpackages=False):
    total = 0
    for dirpath, dirnames, filenames in os.walk(root):
        if skip_subpackages and Path(dirpath).name == "subpackages":
            dirnames[:] = []
            continue
        for name in filenames:
            p = Path(dirpath) / name
            try:
                total += p.stat().st_size
            except OSError:
                pass
    return total

def build_file_hashes(build_dir):
    out = {}
    for rel in BUILD_FILES:
        p = build_dir / rel
        if not p.is_file():
            raise SystemExit("BUILD_FILE_MISSING: " + str(p))
        out[rel] = {"size": p.stat().st_size, "sha256": sha256(p)}
    return out

def seal(root, build_dir, info_out, manifest_out):
    verify_sources(root)
    if not build_dir.is_dir():
        raise SystemExit("BUILD_DIR_MISSING: " + str(build_dir))
    if (build_dir / "subpackages").is_dir():
        bg = build_dir / "subpackages" / "bg"
        bg_bytes = measure_dir(bg) if bg.is_dir() else 0
    else:
        bg_bytes = 0
    main_bytes = measure_dir(build_dir, skip_subpackages=True)
    total_bytes = measure_dir(build_dir, skip_subpackages=False)
    files = build_file_hashes(build_dir)

    if info_out.exists():
        raise SystemExit("INFO_EXISTS: " + str(info_out))
    if manifest_out.exists():
        raise SystemExit("MANIFEST_EXISTS: " + str(manifest_out))

    built_at = datetime.now(timezone.utc).isoformat()
    info = {
        "version": EXPECTED_VERSION,
        "tag": EXPECTED_TAG,
        "commit": EXPECTED_COMMIT,
        "mainPackageBytes": main_bytes,
        "mainPackageKB": round(main_bytes / 1024.0, 1),
        "bgSubpackageBytes": bg_bytes,
        "totalBytes": total_bytes,
        "builtAt": built_at,
        "mainPackageLimitKB": 3950,
        "withinLimit": main_bytes < 3950 * 1024,
    }
    info_out.parent.mkdir(parents=True, exist_ok=True)
    with open(info_out, "x", encoding="utf-8") as f:
        json.dump(info, f, ensure_ascii=False, indent=2)
        f.write("\n")

    manifest = {
        "commit": EXPECTED_COMMIT,
        "short": EXPECTED_SHORT,
        "version": EXPECTED_VERSION,
        "tag": EXPECTED_TAG,
        "builtAt": built_at,
        "source_scripts": {
            rel: {"sha256": expected} for rel, expected in SOURCE_SCRIPTS.items()
        },
        "build_files": files,
    }
    with open(manifest_out, "x", encoding="utf-8") as f:
        json.dump(manifest, f, ensure_ascii=False, indent=2)
        f.write("\n")

    print("INFO_WRITTEN: " + str(info_out))
    print("MANIFEST_WRITTEN: " + str(manifest_out))
    print("MAIN_BYTES: " + str(main_bytes))
    print("WITHIN_LIMIT: " + str(info["withinLimit"]))

def main():
    parser = argparse.ArgumentParser()
    sub = parser.add_subparsers(dest="mode", required=True)
    v = sub.add_parser("version")
    v.add_argument("--approved", action="store_true")
    v.add_argument("--project-root", required=True)
    s = sub.add_parser("seal")
    s.add_argument("--approved", action="store_true")
    s.add_argument("--project-root", required=True)
    s.add_argument("--build-dir", required=True)
    s.add_argument("--info-out", required=True)
    s.add_argument("--manifest-out", required=True)
    args = parser.parse_args()

    if not args.approved:
        raise SystemExit("HOLD: --approved required")

    root = require_new_copy(Path(args.project_root))
    if args.mode == "version":
        write_version(root)
        return

    seal(root, Path(args.build_dir), Path(args.info_out), Path(args.manifest_out))

if __name__ == "__main__":
    main()
